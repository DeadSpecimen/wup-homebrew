#!/usr/bin/env python3
"""Rasterise anti-aliased fonts for the GamePad UI into a C header (4-bit alpha glyphs).

    python3 tools/mkfont_aa.py [out.h]        (default build/gen/font_aa.h; needs Pillow)

Fonts: Inter (SIL Open Font License 1.1, fonts/Inter-LICENSE.txt). Each face/size covers ASCII
32..126. Glyph = cropped coverage bitmap, 2 pixels per byte (high nibble first), offsets from the pen
position on the baseline, advance in 1/4 px so spacing does not drift."""
import os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools')); import paths
FONTS = paths.FONTS
# name, file, pixel size
FACES = [('font_small', 'Inter-Medium.ttf', 16), ('font_body', 'Inter-Medium.ttf', 20),
         ('font_label', 'Inter-SemiBold.ttf', 24), ('font_title', 'Inter-SemiBold.ttf', 32),
         ('font_big', 'Inter-Bold.ttf', 44)]
FIRST, LAST = 32, 126


def face(name, path, size):
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv4 = int(round(f.getlength(ch) * 4))
        l, t, r, b = f.getbbox(ch, anchor='ls')          # relative to the pen on the baseline
        w, h = max(0, r - l), max(0, b - t)
        off = len(bits)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor='ls')
            px = im.load()
            for y in range(h):
                row = [(px[x, y] + 8) // 17 for x in range(w)]         # 0..15
                if w & 1: row.append(0)
                for i in range(0, len(row), 2): bits.append(row[i] << 4 | row[i + 1])
        glyphs.append((off, w, h, l, t, adv4))
    out = ['#ifdef FONT_AA_IMPL', 'static const glyph_t %s_g[%d] = {' % (name, LAST - FIRST + 1)]
    for c, (off, w, h, l, t, adv4) in zip(range(FIRST, LAST + 1), glyphs):
        out.append('  {%d, %d, %d, %d, %d, %d},  /* %r */' % (off, w, h, l, t, adv4, chr(c)))
    out.append('};')
    out.append('static const unsigned char %s_bits[%d] = {' % (name, len(bits)))
    for i in range(0, len(bits), 24): out.append('  ' + ','.join('%d' % v for v in bits[i:i + 24]) + ',')
    out.append('};')
    out.append('const font_t %s = { %d, %d, %d, %s_g, %s_bits };' % (name, size, ascent, ascent + descent, name, name))
    out.append('#else')
    out.append('extern const font_t %s;' % name)
    out.append('#endif')
    return '\n'.join(out), len(bits)


def main():
    dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(paths.out('gen'), 'font_aa.h')
    parts = ['/* generated by tools/mkfont_aa.py from Inter (SIL OFL 1.1, fonts/Inter-LICENSE.txt) */',
             '#pragma once',
             'typedef struct { unsigned int off : 20; unsigned int w : 6; unsigned int h : 6; signed char x, y; unsigned short adv4; } glyph_t;',
             'typedef struct { unsigned char size, ascent, line; const glyph_t *g; const unsigned char *bits; } font_t;',
             '#define FONT_FIRST %d' % FIRST, '#define FONT_LAST %d' % LAST,
             '/* the glyph data is compiled once, in fonts.c (#define FONT_AA_IMPL); everyone else sees declarations */']
    total = 0
    for name, file, size in FACES:
        src, n = face(name, os.path.join(FONTS, file), size)
        parts.append(src); total += n
    open(dst, 'w').write('\n'.join(parts) + '\n')
    print('%s: %d faces, %d bytes of glyph data' % (dst, len(FACES), total))


if __name__ == '__main__':
    main()
